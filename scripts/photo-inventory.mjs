// Writes PHOTO-INVENTORY.md from the registry + asset-sources.json, so it can't drift.
// Run: npm run photo-inventory
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { albums, photoDims, photoLibrary, missingPhotos } from '../src/data/photoLibrary.ts';

const here = dirname(fileURLToPath(import.meta.url));
const src = JSON.parse(readFileSync(resolve(here, 'asset-sources.json'), 'utf8'));
const dot = (iso) => (iso ? iso.split('-').reverse().join('.') : '');
const date = (p) => (p.verifiedDate ? `${dot(p.verifiedDate)} (verified)` : p.eventDate ? `${dot(p.eventDate)} (event)` : p.fileDate ? `≈ ${dot(p.fileDate)} (file date)` : 'unknown');
const orient = (p) => {
  const d = photoDims[p.id];
  if (!d) return '?';
  const r = d.w / d.h;
  return r > 1.1 ? 'landscape' : r < 0.9 ? 'portrait' : 'square';
};
const albumName = (id) => albums.find((a) => a.id === id)?.title ?? id;

const rows = photoLibrary.map((p) => {
  const s = src.photos[p.id];
  const d = photoDims[p.id];
  const edit = d?.edit ? `${d.edit.approved ? 'shown' : '**awaiting approval**'}: removes ${d.edit.removes}` : '—';
  const orientNote = s?.rotate ? `${orient(p)} (rotated ${s.rotate}°)` : orient(p);
  return `| ${p.id} | ${p.title} | ${p.kind === 'video-still' ? 'video still' : 'photo'} | ${date(p)} | ${p.eventAssociation} | ${p.albumIds.map(albumName).join(', ')}${p.eventAssociation === 'unassigned' ? ', Unsorted' : ''} | ${orientNote} | ${edit} | ${[p.private ? 'private' : '', p.secret ? `secret (${p.secret})` : ''].filter(Boolean).join(', ') || '—'} |`;
});

const excluded = Object.entries(src.excluded).map(([id, e]) => `| ${id} | ${e.reason} |`);
const albumRows = albums.map((a) => {
  const n = a.id === 'unsorted' ? photoLibrary.filter((p) => p.eventAssociation === 'unassigned').length : photoLibrary.filter((p) => p.albumIds.includes(a.id)).length;
  return `| ${a.no} | ${a.title} | ${n} | ${a.private ? 'private · ' : ''}${a.blurb}${a.memoryCards ? ` (+${a.memoryCards.length} memory cards without photos)` : ''} |`;
});

const md = `# REVA.EXE · Photo inventory

Generated by \`npm run photo-inventory\` from \`src/data/photoLibrary.ts\` and \`scripts/asset-sources.json\`. A visual contact sheet of every original (used and excluded) is at \`docs/contact-sheet.jpg\` (\`npm run contact-sheet\`).

**Totals:** ${photoLibrary.length} photographs in the library (${photoLibrary.filter((p) => p.kind === 'video-still').length} of them stills from Ruru’s flower-making videos) · ${Object.keys(src.excluded).length} excluded · ${missingPhotos.length} still missing.

**Rules:** Originals in \`../Birthday\` are only read. Web copies in \`public/assets/photos/\` are re-encoded WebP with all EXIF/GPS metadata stripped and semantic file names (no source file names are shipped). Edits are separate derivatives, and every edit says what it removes.

## Library

| ID | Title | Kind | Date | Event | Albums | Orientation | Edit | Flags |
|---|---|---|---|---|---|---|---|---|
${rows.join('\n')}

## Albums

| No | Album | Photos | Notes |
|---|---|---|---|
${albumRows.join('\n')}

## Unresolved associations (kept unassigned on purpose)

| ID | What it shows | Lead, not established |
|---|---|---|
| P15 | Pickleball court, paddle | media-index: “plausible” morning of 27 Jun (she mentioned a court near Sukhna). **Not shown as the lake.** |
| P04 | Rooftop at night | media-index: “plausible” 6 May (same dress as P12–P14) |
| P23 | Olive jacket, old building | media-index: “plausible” same day as P20 (same jacket) |
| P20 | The almirahs | Context confirmed (her 14 Jun message); date unknown (“winter; older photo”) |
| P07, P11 | Together, undated | No event or date |
| All other portraits | Solo portraits | Undated |

## Excluded

| ID | Reason |
|---|---|
${excluded.join('\n')}

## Not yet in the project

${missingPhotos.map((m) => `- **${m.title}**: ${m.note}`).join('\n')}
- **First date (27 Apr):** no photograph in the approved set. The Wishes review notes it exists only as two of Reva’s own selfie videos (\`39840\`, \`39851\`), which are not in this project.
- **Sukhna lake (27 Jun):** no photograph found anywhere.

## Candidates awaiting your approval (not used)

\`Wishes/shortlist/public\` (31 photos) and \`Wishes/shortlist/private\` (31 photos) come from the separate Wishes project’s review of 3,030 chat photos. They were never approved for REVA.EXE, and their file names are WhatsApp send dates, not capture dates, so none were used. Say the word and I’ll review them for the library, keeping the same rules (unassigned unless the event is proven).
`;
writeFileSync(resolve(here, '../PHOTO-INVENTORY.md'), md);
console.log('✓ PHOTO-INVENTORY.md');
